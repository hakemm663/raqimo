export function generateContextualAIInsights(data: WorkspaceSnapshot, todayISO: string): AIInsightItem[] {
  const insights: AIInsightItem[] = [];

  // Overdue follow-up check
  const overdueFollowUp = data.activities.find(
    (a) => a.type === "Follow-up" && a.status !== "completed" && (a.dueAt || a.occurredAt) < todayISO
  );
  if (overdueFollowUp) {
    insights.push({
      id: "ai_overdue_fu",
      module: "crm",
      severity: "warning",
      titleEn: `Overdue follow-up: ${overdueFollowUp.title}`,
      titleAr: `متابعة متأخرة: ${overdueFollowUp.title}`,
      descriptionEn: "This customer interaction passed its scheduled follow-up date and may cool down if left unaddressed.",
      descriptionAr: "تجاوز هذا الإجراء موعد المتابعة المحدد وقد يضعف فرص إغلاق الصفقة إذا تأخر الرد.",
      suggestedActionEn: "Review Follow-ups",
      suggestedActionAr: "مراجعة المتابعات",
      targetSection: "crm-followups",
    });
  }

  // New lead without contact
  const untouchedLead = data.leads.find((l) => !l.archived && l.status === "New" && !l.lastContactDate);
  if (untouchedLead) {
    insights.push({
      id: "ai_untouched_lead",
      module: "crm",
      severity: "opportunity",
      titleEn: `Promising lead awaiting first contact: ${untouchedLead.name}`,
      titleAr: `عميل محتمل واعد بانتظار أول تواصل: ${untouchedLead.name}`,
      descriptionEn: `${untouchedLead.companyName} (${untouchedLead.source}) has an estimated value of $${untouchedLead.estimatedValue.toLocaleString()} and score ${untouchedLead.score}/100.`,
      descriptionAr: `شركة ${untouchedLead.companyName} بقيمة تقديرية $${untouchedLead.estimatedValue.toLocaleString()} وتقييم ${untouchedLead.score}/100.`,
      suggestedActionEn: "Open Leads",
      suggestedActionAr: "فتح العملاء المحتملين",
      entityType: "lead",
      entityId: untouchedLead.id,
      targetSection: "crm-leads",
    });
  }

  // Blocked task
  const blockedTask = data.tasks.find((t) => t.status === "Blocked" || (t.dependencyIds?.length ?? 0) > 0);
  if (blockedTask) {
    insights.push({
      id: "ai_blocked_task",
      module: "tasks",
      severity: "warning",
      titleEn: `Dependency bottleneck: ${blockedTask.title}`,
      titleAr: `مهمة معتمدة على أخرى: ${blockedTask.title}`,
      descriptionEn: "Completing its blocking task unlocks the next milestone in the project timeline.",
      descriptionAr: "إنهاء المهمة المانعة سيفتح المجال لإكمال المرحلة التالية في الجدول الزمني.",
      suggestedActionEn: "Inspect My Tasks",
      suggestedActionAr: "عرض المهام",
      targetSection: "tasks-my",
    });
  }

  // Unpaid invoice cross-module insight
  const unpaidInv = data.invoices.find((inv) => inv.amount > inv.paidAmount);
  if (unpaidInv) {
    insights.push({
      id: "ai_unpaid_inv",
      module: "cross",
      severity: "info",
      titleEn: `Outstanding invoice linked to NileCraft ($${(unpaidInv.amount - unpaidInv.paidAmount).toLocaleString()})`,
      titleAr: `فاتورة مستحقة مرتبطة بشركة NileCraft ($${(unpaidInv.amount - unpaidInv.paidAmount).toLocaleString()})`,
      descriptionEn: "NileCraft Commerce has an active project and an open Q1 retainer deal alongside an open invoice.",
      descriptionAr: "شركة NileCraft لديها مشروع نشط وصفقة تجديد بالإضافة إلى فاتورة لم تُسدد بعد.",
      suggestedActionEn: "View Contacts & Invoices",
      suggestedActionAr: "عرض جهات الاتصال والفواتير",
      targetSection: "crm-contacts",
    });
  }

  return insights;
}
